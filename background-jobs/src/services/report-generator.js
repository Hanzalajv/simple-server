import PDFDocument from 'pdfkit';
import { createWriteStream } from 'fs';
import { mkdirSync, existsSync } from 'fs';
import { join } from 'path';
import Database from 'better-sqlite3';

const REPORTS_DIR = join(process.cwd(), 'reports');

export async function generateReport(jobId) {
  if (!existsSync(REPORTS_DIR)) {
    mkdirSync(REPORTS_DIR, { recursive: true });
  }

  const db = new Database('jobs.db');
  
  const totalJobs = db.prepare('SELECT COUNT(*) as count FROM jobs').get();
  const completedJobs = db.prepare("SELECT COUNT(*) as count FROM jobs WHERE status = 'completed'").get();
  const failedJobs = db.prepare("SELECT COUNT(*) as count FROM jobs WHERE status = 'failed'").get();
  const pendingJobs = db.prepare("SELECT COUNT(*) as count FROM jobs WHERE status = 'pending'").get();
  const recentJobs = db.prepare("SELECT * FROM jobs ORDER BY created_at DESC LIMIT 10").all();
  
  db.close();

  const doc = new PDFDocument({ size: 'A4', margin: 50 });
  const filePath = join(REPORTS_DIR, `report-${jobId}.pdf`);
  
  const writeStream = createWriteStream(filePath);
  doc.pipe(writeStream);

  // Header
  doc.fontSize(24).font('Helvetica-Bold').text('Job Processing Report', { align: 'center' });
  doc.moveDown(0.5);
  doc.fontSize(12).font('Helvetica').text(`Generated: ${new Date().toISOString()}`, { align: 'center' });
  doc.moveDown(1);

  // Divider
  doc.moveTo(50, doc.y).lineTo(545, doc.y).stroke('#C4A962');
  doc.moveDown(1);

  // Summary section
  doc.fontSize(16).font('Helvetica-Bold').text('Summary', { underline: true });
  doc.moveDown(0.5);
  doc.fontSize(12).font('Helvetica');

  const summaryData = [
    ['Total Jobs', totalJobs.count.toString()],
    ['Completed', completedJobs.count.toString()],
    ['Failed', failedJobs.count.toString()],
    ['Pending', pendingJobs.count.toString()],
  ];

  summaryData.forEach(([label, value]) => {
    doc.font('Helvetica-Bold').text(`${label}: `, { continued: true });
    doc.font('Helvetica').text(value);
  });

  doc.moveDown(1);

  // Recent jobs section
  doc.fontSize(16).font('Helvetica-Bold').text('Recent Jobs', { underline: true });
  doc.moveDown(0.5);

  if (recentJobs.length === 0) {
    doc.fontSize(12).font('Helvetica').text('No jobs found.');
  } else {
    doc.fontSize(10).font('Helvetica-Bold');
    doc.text('Job ID', 50, doc.y, { width: 200 });
    doc.text('Status', 250, doc.y - 12, { width: 100 });
    doc.text('Created', 350, doc.y - 12, { width: 150 });
    doc.moveDown(0.5);

    doc.font('Helvetica');
    recentJobs.forEach(job => {
      const shortId = job.id.substring(0, 8);
      doc.text(shortId, 50, doc.y, { width: 200 });
      doc.text(job.status, 250, doc.y - 12, { width: 100 });
      doc.text(job.created_at, 350, doc.y - 12, { width: 150 });
      doc.moveDown(0.3);
    });
  }

  doc.moveDown(1);
  doc.moveTo(50, doc.y).lineTo(545, doc.y).stroke('#C4A962');
  doc.moveDown(0.5);

  // Footer
  doc.fontSize(10).font('Helvetica').text('Generated by Background Jobs System', { align: 'center' });

  doc.end();

  return new Promise((resolve) => {
    writeStream.on('finish', () => {
      resolve(`/reports/report-${jobId}.pdf`);
    });
  });
}